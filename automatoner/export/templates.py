HANDLER = '''"""AWS Lambda handler generated by Automatoner. Runs a tabular model with ONNX Runtime.

Event shapes accepted:
  {"record": {...}}            one record, the keys are the feature columns
  {"records": [{...}, ...]}    a batch
  SQS / EventBridge: put the record in the message body or in `detail` as JSON.
Returns {"results": [{"score": 0.0-1.0, "is_anomaly": bool, "reason": "..."} ...]} for anomaly models and
{"results": [{"label": "...", "probability": 0.93, "probabilities": {...}} ...]} for classifiers.
"""
import json
import os

import numpy as np
import onnxruntime as ort

HERE = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(HERE, "features.json")) as f:
    FEATURES = json.load(f)
with open(os.path.join(HERE, "inference.json")) as f:
    INFER = json.load(f)

_so = ort.SessionOptions()
_so.intra_op_num_threads = 1
SESSION = ort.InferenceSession(os.path.join(HERE, "model.onnx"), _so, providers=["CPUExecutionProvider"])  # loaded once per container
INPUT = SESSION.get_inputs()[0].name


def transform(records):
    rows = []
    for r in records:
        v = []
        for c in FEATURES["numeric"]:
            x = r.get(c)
            x = FEATURES["median"][c] if x is None or x == "" else float(x)
            v.append((x - FEATURES["mean"][c]) / FEATURES["std"][c])
        for c, values in FEATURES["categorical"].items():
            s = str(r.get(c))
            v.extend(1.0 if s == val else 0.0 for val in values)
        rows.append(v)
    return np.asarray(rows, dtype=np.float32)


def _records(event):
    if isinstance(event, dict) and "Records" in event:  # SQS
        return [json.loads(m["body"]) for m in event["Records"]]
    if isinstance(event, dict) and "detail" in event:   # EventBridge
        d = event["detail"]
        return [d] if isinstance(d, dict) else [json.loads(d)]
    if isinstance(event, dict) and "records" in event:
        return event["records"]
    if isinstance(event, dict) and "record" in event:
        return [event["record"]]
    raise ValueError("send {\\"record\\": {...}} or {\\"records\\": [...]}")


def _reason(x_row):
    z = np.abs(x_row[: len(FEATURES["numeric"])])
    if z.size == 0:
        return ""
    i = int(z.argmax())
    name = FEATURES["numeric"][i]
    direction = "high" if x_row[i] > 0 else "low"
    return f"{name} is unusually {direction} ({x_row[i]:+.1f} standard deviations from normal)"


def handler(event, context=None):
    records = _records(event)
    X = transform(records)
    out = SESSION.run([INFER["onnx_output"]], {INPUT: X})[0]
    results = []
    if INFER["mode"] == "anomaly":
        raw = INFER["raw_sign"] * np.asarray(out, dtype=float).reshape(-1)
        score = np.clip((raw - INFER["lo"]) / (INFER["hi"] - INFER["lo"]), 0.0, 1.0)
        for s, x in zip(score, X):
            flag = bool(s >= INFER["threshold"])
            results.append({"score": round(float(s), 4), "is_anomaly": flag, "reason": _reason(x) if flag else ""})
    else:
        probs = np.asarray(out, dtype=float)
        classes = INFER["classes"]
        for p in probs:
            i = int(p.argmax())
            results.append({"label": classes[i], "probability": round(float(p[i]), 4),
                            "probabilities": {c: round(float(v), 4) for c, v in zip(classes, p)}})
    return {"results": results}
'''

