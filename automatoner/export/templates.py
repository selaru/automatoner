bundle = joblib.load("model.joblib")
model, F, INFER = bundle["model"], bundle["features"], bundle["inference"]


def transform(records):
    rows = []
    for r in records:
        v = []
        for c in F["numeric"]:
            x = r.get(c)
            x = F["median"][c] if x is None or x == "" else float(x)
