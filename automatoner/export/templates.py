TEXT_HANDLER = '''"""AWS Lambda handler for a text classifier, generated by Automatoner. ONNX Runtime plus the `tokenizers` library."""
import json
import os

import numpy as np
import onnxruntime as ort
from tokenizers import Tokenizer

HERE = os.path.dirname(os.path.abspath(__file__))
INFER = json.load(open(os.path.join(HERE, "inference.json")))
TOK = Tokenizer.from_file(os.path.join(HERE, "tokenizer.json"))
TOK.enable_truncation(max_length=INFER["max_length"])
TOK.enable_padding(pad_id=INFER.get("pad_id", 0), pad_token=INFER.get("pad_token", "[PAD]"))
_so = ort.SessionOptions()
_so.intra_op_num_threads = 1
SESSION = ort.InferenceSession(os.path.join(HERE, "model.onnx"), _so, providers=["CPUExecutionProvider"])
NAMES = {i.name for i in SESSION.get_inputs()}


def _texts(event):
    if isinstance(event, dict) and "Records" in event:
        return [json.loads(m["body"]).get("text", m["body"]) if m["body"].startswith("{") else m["body"] for m in event["Records"]]
    if isinstance(event, dict) and "texts" in event:
        return event["texts"]
    if isinstance(event, dict) and "text" in event:
        return [event["text"]]
    raise ValueError('send {"text": "..."} or {"texts": [...]}')


def handler(event, context=None):
    texts = _texts(event)
    enc = TOK.encode_batch(texts)
    feeds = {"input_ids": np.array([e.ids for e in enc], dtype=np.int64), "attention_mask": np.array([e.attention_mask for e in enc], dtype=np.int64)}
    feeds = {k: v for k, v in feeds.items() if k in NAMES}
    logits = SESSION.run([INFER["onnx_output"]], feeds)[0]
    z = logits - logits.max(axis=1, keepdims=True)
    p = np.exp(z) / np.exp(z).sum(axis=1, keepdims=True)
    classes = INFER["classes"]
    return {"results": [{"label": classes[int(r.argmax())], "probability": round(float(r.max()), 4),
                         "probabilities": {c: round(float(v), 4) for c, v in zip(classes, r)}} for r in p]}
'''

